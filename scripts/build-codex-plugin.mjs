// Builds the self-contained Codex plugin in plugins/tldraw/.
//
// Codex installs a plugin by copying its directory into its own cache and
// running the MCP command from there, with no `npm install` step. So the
// plugin has to carry everything it needs:
//
//   plugins/tldraw/server/tldraw-mcp.mjs   server + all npm deps, one file
//   plugins/tldraw/server/THIRD_PARTY_LICENSES.txt   licenses of those deps
//   plugins/tldraw/public/                 the built tldraw canvas
//   plugins/tldraw/skills/tldraw/SKILL.md  copied from .claude/skills/tldraw
//
// Run after `npm run build:web` (the canvas must already be built):
//
//   node scripts/build-codex-plugin.mjs           # (re)build the plugin
//   node scripts/build-codex-plugin.mjs --check   # fail if it is out of date

import { build } from "esbuild";
import { cp, mkdir, mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PLUGIN = join(ROOT, "plugins", "tldraw");
const CHECK = process.argv.includes("--check");

const SERVER_ENTRY = join(ROOT, "packages", "server", "src", "index.ts");
const PUBLIC_SRC = join(ROOT, "packages", "server", "public");
const SKILL_SRC = join(ROOT, ".claude", "skills", "tldraw", "SKILL.md");

async function generate(outDir) {
  if (!(await exists(join(PUBLIC_SRC, "index.html")))) {
    throw new Error(
      `${relative(ROOT, PUBLIC_SRC)}/index.html is missing. Run \`npm run build:web\` first.`
    );
  }

  const result = await build({
    // Pin the working dir: esbuild writes source paths into the bundle as
    // comments, and --check needs byte-identical output from anywhere.
    absWorkingDir: ROOT,
    metafile: true,
    entryPoints: [SERVER_ENTRY],
    outfile: join(outDir, "server", "tldraw-mcp.mjs"),
    bundle: true,
    platform: "node",
    target: "node20",
    format: "esm",
    // `ws` loads these native speed-ups inside try/catch and falls back to
    // pure JS when they're absent, so leave them out of the bundle.
    external: ["bufferutil", "utf-8-validate"],
    // Bundled CommonJS deps (ws) call require() for Node built-ins, which an
    // ES module doesn't have. Give the bundle one.
    banner: {
      js: [
        "// tldraw-mcp: bundled MCP server for the Codex plugin. Generated by",
        "// scripts/build-codex-plugin.mjs from packages/server/src. Do not edit.",
        'import { createRequire as __tldrawCreateRequire } from "node:module";',
        "const require = __tldrawCreateRequire(import.meta.url);"
      ].join("\n")
    },
    legalComments: "eof",
    logLevel: "warning"
  });

  await writeFile(
    join(outDir, "server", "THIRD_PARTY_LICENSES.txt"),
    await thirdPartyLicenses(Object.keys(result.metafile.inputs))
  );

  // httpHost resolves the canvas as ../public relative to the running file,
  // which for the bundle is plugins/tldraw/public.
  await cp(PUBLIC_SRC, join(outDir, "public"), { recursive: true });
  await mkdir(join(outDir, "skills", "tldraw"), { recursive: true });
  await cp(SKILL_SRC, join(outDir, "skills", "tldraw", "SKILL.md"));
}

/**
 * The bundle redistributes its npm dependencies, so ship their licenses with
 * it. One entry per package that actually ended up in the bundle.
 */
async function thirdPartyLicenses(inputs) {
  const dirs = new Set();
  for (const input of inputs) {
    const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (m) dirs.add(m[1]);
  }
  const entries = [];
  for (const dir of [...dirs].sort()) {
    const pkg = JSON.parse(await readFile(join(ROOT, dir, "package.json"), "utf8"));
    const licenseFile = (await readdir(join(ROOT, dir))).find((f) => /^(licen[cs]e|copying)/i.test(f));
    const text = licenseFile
      ? (await readFile(join(ROOT, dir, licenseFile), "utf8")).trim()
      : `License: ${pkg.license ?? "see package"} (no license file shipped with the package)`;
    entries.push(`${pkg.name}@${pkg.version} (${pkg.license ?? "unknown"})\n\n${text}`);
  }
  const rule = "\n\n" + "-".repeat(78) + "\n\n";
  return (
    "Third-party software bundled into tldraw-mcp.mjs\n" + rule + entries.join(rule) + "\n"
  );
}

/** Generated paths inside the plugin; everything else there is hand-written. */
const GENERATED = ["server", "public", join("skills", "tldraw", "SKILL.md")];

async function main() {
  if (!CHECK) {
    for (const p of GENERATED) await rm(join(PLUGIN, p), { recursive: true, force: true });
    await generate(PLUGIN);
    console.log(`built ${relative(ROOT, PLUGIN)}`);
    return;
  }

  const tmp = await mkdtemp(join(tmpdir(), "tldraw-plugin-"));
  try {
    await generate(tmp);
    const stale = [];
    for (const p of GENERATED) {
      const a = await listFiles(join(tmp, p));
      const b = await listFiles(join(PLUGIN, p));
      for (const f of new Set([...a.keys(), ...b.keys()])) {
        if (!a.has(f) || !b.has(f) || !a.get(f).equals(b.get(f))) stale.push(join(p, f));
      }
    }
    if (stale.length) {
      console.error(
        "plugins/tldraw is out of date. Run `npm run build` and commit the result.\n" +
          stale.map((f) => `  ${f}`).join("\n")
      );
      process.exit(1);
    }
    console.log("plugins/tldraw is up to date");
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

async function listFiles(path, base = path, out = new Map()) {
  let s;
  try { s = await stat(path); } catch { return out; }
  if (s.isFile()) {
    out.set(relative(base, path) || ".", await readFile(path));
    return out;
  }
  for (const name of await readdir(path)) await listFiles(join(path, name), base, out);
  return out;
}

async function exists(p) {
  try { await stat(p); return true; } catch { return false; }
}

main().catch((err) => {
  console.error(err?.message ?? err);
  process.exit(1);
});
